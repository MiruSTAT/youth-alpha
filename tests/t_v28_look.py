# v28 program settings: super admin card, saving, applying (title, font, size, parts off, wording)
from playwright.sync_api import sync_playwright
V='/home/claude/youth-alpha/vendor/'; U='http://localhost:8766/'; errs=[]
SEED=open('/tmp/t35.py').read().split('SEED="""')[1].split('"""')[0]
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-gl=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'])
    cx=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True,service_workers='block')
    cx.add_init_script(SEED); pg=cx.new_page()
    pg.route('**/three.module.min.js', lambda r: r.fulfill(path=V+'three.module.min.js', content_type='application/javascript'))
    pg.route('**/fonts.googleapis.com/**', lambda r: r.fulfill(body='', content_type='text/css'))
    pg.route('**/supabase.js', lambda r: r.fulfill(body='', content_type='application/javascript'))
    pg.on('pageerror',lambda e: errs.append('PAGEERR '+str(e)))
    pg.on('console',lambda m: errs.append('CONSOLE '+m.text) if m.type=='error' and 'Failed to load' not in m.text else None)
    def go(h,w=1300): pg.goto(U+h); pg.wait_for_timeout(w)
    go('#/', 1500); print('before:', pg.inner_text('.brand'), '| nav:', pg.eval_on_selector_all('.kid-nav a','e=>e.filter(x=>getComputedStyle(x).display!="none").map(x=>x.dataset.nav)'))
    go('#/admin/look', 1800)
    pg.evaluate("document.querySelector('#lookCard').scrollIntoView()"); pg.screenshot(path='/tmp/s23/60_look.png')
    pg.fill('#lookForm [name=title]', 'Easter Kids'); pg.fill('#lookForm [name=emoji]', '🐣')
    pg.select_option('#lookForm [name=pack]', 'plain'); pg.select_option('#lookForm [name=font]', 'kanit')
    pg.eval_on_selector('#lookForm [name=size]', 'e=>{e.value="1.2"; e.dispatchEvent(new Event("input"))}')
    print('size label:', pg.inner_text('#lookSizeV'), '| scene after pack:', pg.input_value('#lookForm [name=p_scene]'))
    pg.uncheck('#lookForm [name=f_shop]'); pg.uncheck('#lookForm [name=f_bible]')
    pg.click('#lookForm details summary'); pg.fill('#lookForm [name=th_ranking]', 'คะแนนรวม'); pg.fill('#lookForm [name=en_ranking]', 'Scores')
    pg.screenshot(path='/tmp/s23/61_look_filled.png', full_page=True)
    pg.click('#lookForm [type=submit]'); pg.wait_for_timeout(700)
    print('toast:', pg.inner_text('#toast'), '| brand now:', pg.inner_text('.brand'), '| title:', pg.title())
    print('font var:', pg.evaluate("getComputedStyle(document.documentElement).getPropertyValue('--font')"), '| html size:', pg.evaluate("getComputedStyle(document.documentElement).fontSize"))
    go('#/', 1800)
    print('after reload brand:', pg.inner_text('.brand'), '| nav:', pg.eval_on_selector_all('.kid-nav a','e=>e.filter(x=>getComputedStyle(x).display!="none").map(x=>x.innerText.replace("\\n"," "))'))
    print('scene shown:', pg.evaluate("getComputedStyle(document.querySelector('#scene')).display"), '| pack:', pg.evaluate('document.body.dataset.pack'))
    pg.screenshot(path='/tmp/s23/62_kid_after.png')
    go('#/shop', 1200); print('shop redirect ->', pg.evaluate('location.hash'))
    go('#/menu', 1200); print('menu rows:', pg.eval_on_selector_all('.mrow','e=>e.map(x=>x.dataset.m||"adult")'))
    go('#/songs', 1500); print('songs title:', pg.inner_text('.sheet-title') if pg.locator('.sheet-title').count() else pg.evaluate('location.hash'))
    go('#/menu', 1200); pg.click('[data-m=lang]'); pg.wait_for_timeout(600); print('EN nav:', pg.eval_on_selector_all('.kid-nav a b','e=>e.map(x=>x.innerText)'))
    go('#/admin/look', 1800); print('form keeps values:', pg.input_value('#lookForm [name=title]'), pg.input_value('#lookForm [name=font]'), pg.is_checked('#lookForm [name=f_shop]'))
    b.close()
print('\n'.join(errs) or 'no errors')
