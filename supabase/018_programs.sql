-- =====================================================================
-- Youth Alpha — update 18: PROGRAMS. One database, many programs (Youth Alpha Christmas, an Easter
-- program, …), each with its own link (?p=<slug>), its own people, points, attendance, shop, songs,
-- point categories, feedback, activity log and settings. Safe to re-run.
--
--  * Everything that existed before becomes program 1 ("Youth Alpha Christmas 2026"): every new
--    program_id column defaults to 1, so no existing row changes meaning and nothing is deleted.
--  * Program 1 is also what the plain link (no ?p=) opens, so old links and the printed QR still work.
--  * settings: one row per program, settings.id = programs.id (program 1 keeps its row id 1).
--  * attendance / points / redemptions take program_id from their kid (trigger program_from_kid).
--  * point_categories keep a globally unique key. A copied program gets the same categories with the
--    suffix _p<id> (attendance_p2, bonus_p2, …); the base key (without the suffix) keeps the special
--    meaning (attendance points, bonus must be positive).
--  * Staff (admins / editors) are shared by all programs. Programs are created, renamed and archived
--    only by the super admin (program_create / program_update). Programs are never deleted.
-- =====================================================================

-- ---------- programs
create table if not exists public.programs (
  id          int generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,39}$'),
  name        text not null check (char_length(name) between 1 and 60),
  archived    boolean not null default false,
  copied_from int references public.programs(id),
  look        jsonb not null default '{}'::jsonb,      -- program settings (name on screen, theme pack, font, …), used from v28
  created_at  timestamptz not null default now()
);
insert into public.programs (id, slug, name) overriding system value
values (1, 'youth-alpha-christmas-2026', 'Youth Alpha Christmas 2026') on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.programs', 'id'), greatest((select max(id) from public.programs), 1));

alter table public.programs enable row level security;
revoke all on public.programs from anon, authenticated;
grant select on public.programs to anon, authenticated;
drop policy if exists public_read on public.programs;
create policy public_read on public.programs for select to anon, authenticated using (true);

drop trigger if exists audit_programs on public.programs;
create trigger audit_programs after insert or update or delete on public.programs
for each row execute function public.audit_trigger();

-- ---------- program_id on every program-owned table (existing rows -> program 1)
do $$
declare t text;
begin
  foreach t in array array['kids','point_categories','shop_items','songs','feedback','kid_events',
                           'attendance','attendance_rounds','points','redemptions'] loop
    execute format('alter table public.%I add column if not exists program_id int not null default 1 references public.programs(id)', t);
    execute format('create index if not exists %I on public.%I(program_id)', t || '_program_idx', t);
  end loop;
end $$;

-- attendance rounds: one "finished" marker per program, day and session
alter table public.attendance_rounds drop constraint if exists attendance_rounds_pkey;
alter table public.attendance_rounds add constraint attendance_rounds_pkey primary key (program_id, day, session);

-- settings: one row per program (id = program id)
alter table public.settings drop constraint if exists settings_id_check;

-- bonus points stay positive in every program (bonus, bonus_p2, …)
alter table public.points drop constraint if exists bonus_positive;
alter table public.points add constraint bonus_positive check (regexp_replace(skill, '_p[0-9]+$', '') <> 'bonus' or amount > 0);

-- attendance / points / prizes given: program comes from the kid
create or replace function public.program_from_kid() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  select program_id into new.program_id from public.kids where id = new.kid_id;
  new.program_id := coalesce(new.program_id, 1);
  return new;
end; $$;
do $$
declare t text;
begin
  foreach t in array array['attendance','points','redemptions'] loop
    execute format('drop trigger if exists program_from_kid_trg on public.%I', t);
    execute format('create trigger program_from_kid_trg before insert on public.%I for each row execute function public.program_from_kid()', t);
  end loop;
end $$;

-- attendance points: the kid's program decides how many points and which category key
create or replace function public.sync_attendance_points() returns trigger
language plpgsql security definer set search_path = public as $$
declare pts int; pid int;
begin
  select k.program_id, s.attendance_points into pid, pts
    from public.kids k left join public.settings s on s.id = k.program_id where k.id = new.kid_id;
  delete from public.points where attendance_id = new.id;
  if new.status = 'present' and coalesce(pts, 0) > 0 then
    insert into public.points (kid_id, skill, amount, note, attendance_id, given_by, program_id)
    values (new.kid_id, case when coalesce(pid, 1) = 1 then 'attendance' else 'attendance_p' || pid end,
            pts, to_char(new.day, 'YYYY-MM-DD'), new.id, new.updated_by, coalesce(pid, 1));
  end if;
  return new;
end; $$;

-- ---------- public views get a program_id column (added at the end, so old columns keep their place)
create or replace view public.leaderboard as
select k.id, k.nickname, k.avatar,
  coalesce((select sum(p.amount) from public.points p where p.kid_id = k.id), 0)::int as total,
  coalesce((select sum(r.price) from public.redemptions r where r.kid_id = k.id), 0)::int as spent,
  k.program_id
from public.kids k
where k.active;

create or replace view public.kid_skill_totals as
select p.kid_id, p.skill, p.detail, sum(p.amount)::int as total, k.program_id
from public.points p join public.kids k on k.id = p.kid_id and k.active
group by p.kid_id, p.skill, p.detail, k.program_id;

create or replace view public.event_info as
select event_dow, event_start, event_end, fb_dow, fb_start, fb_end, tip_days, fb_open, music,
       announce, verse_text, verse_ref, install_on, id as program_id
from public.settings;
grant select on public.leaderboard, public.kid_skill_totals, public.event_info to anon, authenticated;

-- ---------- feedback: open / closed per program
create or replace function public.feedback_open(p int) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select fb_open from public.settings where id = p), false);
$$;
grant execute on function public.feedback_open(int) to anon, authenticated;
drop policy if exists kid_insert on public.feedback;
create policy kid_insert on public.feedback for insert to anon, authenticated with check (public.feedback_open(program_id));

-- ---------- announcement + verse per program
drop function if exists public.save_notice(text, text, text);
create or replace function public.save_notice(p_announce text, p_verse_text text, p_verse_ref text, p_program int default 1) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_staff() then raise exception 'staff only'; end if;
  update public.settings set announce = left(btrim(coalesce(p_announce, '')), 160),
    verse_text = left(btrim(coalesce(p_verse_text, '')), 400), verse_ref = left(btrim(coalesce(p_verse_ref, '')), 60)
  where id = p_program;
end; $$;
revoke all on function public.save_notice(text, text, text, int) from public, anon;
grant execute on function public.save_notice(text, text, text, int) to authenticated;

-- ---------- super admin switches per program
drop function if exists public.superadmin_set(text, jsonb);
create or replace function public.superadmin_set(p_key text, p_value jsonb, p_program int default 1) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_superadmin() then raise exception 'super admin only'; end if;
  if p_key = 'install_on' then update public.settings set install_on = (p_value #>> '{}')::boolean where id = p_program;
  else raise exception 'unknown setting %', p_key; end if;
end; $$;
revoke all on function public.superadmin_set(text, jsonb, int) from public, anon;
grant execute on function public.superadmin_set(text, jsonb, int) to authenticated;

-- ---------- clearing the kids' activity log: only the current program's rows
drop function if exists public.clear_kid_events();
create or replace function public.clear_kid_events(p_program int default 1) returns int
language plpgsql security definer set search_path = public, private as $$
declare cnt int;
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  if coalesce((auth.jwt()->>'iat')::bigint, 0) < extract(epoch from now())::bigint - 120
     and not exists (select 1 from private.super_admins where user_id = auth.uid() and pw_ok_at > now() - interval '2 minutes') then
    raise exception 'please re-enter the admin password';
  end if;
  delete from public.kid_events where program_id = p_program;
  get diagnostics cnt = row_count;
  update private.super_admins set pw_ok_at = null where user_id = auth.uid();
  insert into public.audit_log (actor, actor_email, table_name, op, row_key, new_data)
  values (auth.uid(), coalesce((select email from auth.users where id = auth.uid()), ''), 'kid_events', 'CLEAR', p_program::text,
          jsonb_build_object('rows_deleted', cnt, 'program_id', p_program));
  return cnt;
end; $$;
revoke all on function public.clear_kid_events(int) from public, anon;
grant execute on function public.clear_kid_events(int) to authenticated;

-- ---------- create a program (super admin only). Always copies the point categories (renamed _p<id>)
-- and the settings row; optionally the people (without points), the shop, the songs.
create or replace function public.program_create(p_name text, p_slug text, p_from int default 1,
  p_people boolean default false, p_shop boolean default true, p_songs boolean default true) returns json
language plpgsql security definer set search_path = public as $$
declare nid int; base text;
begin
  if not public.is_superadmin() then raise exception 'super admin only'; end if;
  if not exists (select 1 from public.programs where id = p_from) then raise exception 'unknown program %', p_from; end if;
  insert into public.programs (slug, name, copied_from) values (lower(btrim(p_slug)), btrim(p_name), p_from) returning id into nid;

  -- settings: copy the source row, but start with feedback closed and no announcement
  insert into public.settings select (jsonb_populate_record(null::public.settings,
    to_jsonb(s) || jsonb_build_object('id', nid, 'fb_open', false, 'announce', '', 'verse_text', '', 'verse_ref', ''))).*
  from public.settings s where s.id = p_from;

  -- point categories (always; attendance points need the attendance category)
  insert into public.point_categories (key, name_th, name_en, icon, info, details, sort, active, program_id)
  select regexp_replace(key, '_p[0-9]+$', '') || '_p' || nid, name_th, name_en, icon, info, details, sort, active, nid
  from public.point_categories where program_id = p_from;

  if p_people then
    insert into public.kids (nickname, avatar, grp, active, program_id)
    select nickname, avatar, grp, active, nid from public.kids where program_id = p_from and active;
  end if;
  if p_shop then
    insert into public.shop_items (name, icon, price, active, sort, program_id)
    select name, icon, price, active, sort, nid from public.shop_items where program_id = p_from;
  end if;
  if p_songs then
    insert into public.songs (title, subtitle, song_key, bpm, beats, youtube, yt_start, credits, content, sheets, sort, active, sync, opts, program_id)
    select title, subtitle, song_key, bpm, beats, youtube, yt_start, credits, content, sheets, sort, active, sync, opts, nid
    from public.songs where program_id = p_from;
  end if;
  return json_build_object('ok', true, 'id', nid);
end; $$;
revoke all on function public.program_create(text, text, int, boolean, boolean, boolean) from public, anon;
grant execute on function public.program_create(text, text, int, boolean, boolean, boolean) to authenticated;

-- rename / archive (hide) a program. Program 1 cannot be archived. Nothing is ever deleted.
create or replace function public.program_update(p_id int, p_name text, p_archived boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_superadmin() then raise exception 'super admin only'; end if;
  if p_id = 1 and p_archived then raise exception 'program 1 cannot be archived'; end if;
  update public.programs set name = btrim(p_name), archived = p_archived where id = p_id;
end; $$;
revoke all on function public.program_update(int, text, boolean) from public, anon;
grant execute on function public.program_update(int, text, boolean) to authenticated;
